"""構想プレゼンのページ（/genba/concept/）の内容。

元は「genba 構想.pptx」（2026年10月・全23枚）。文言・枚数・順番はプレゼンのまま写している。
プレゼンを更新したら、ここも合わせて直す。

1枚のスライドは {'kind', 'kicker', 'title', 'blocks', 'footer'} の辞書。
kind は 'cover'（表紙）・'part'（章の扉）・'end'（結び）・'slide'（通常）。dark=True の通常スライドは濃い背景にする。
footer はプレゼンの左下の文言で、ファイルの最後でページ位置から付ける。
blocks は上から順に並べる部品で、下の関数で作る：

- cards：カードを横に並べる（cols 列）。grow=False は高さを広げない帯
- steps：段階を順に横に並べる（arrows=True で矢印を挟む）
- diagram：左から右の図（5枚目）。カード → カード → 縦書きの語 → 縦に積んだカード
- table：表（bold_first=True で1列目を太字）
- note：補足。tone='plain' は帯なしの文、lead は太字の書き出し
- flow：矢印でつなぐ箱
- heading：小見出し

カードは title・text・lines（箇条書き。numbered=True で番号付き）・pairs（太字の書き出しと本文の組）・sub（補足）・
chip（下に置く札）・label（上の小見出し）を持てる。big_label は大きな番号、role は立場名を見出しにする形（20枚目）。

カードの色（tone）はプレゼンで強調しているものだけに付ける。'mint' は薄い緑（E3EEE9）に緑の枠、'mint-flat' は枠なしの帯、
'sand' は砂色（ECEAE2）の帯、'sand-line' は砂色に枠。配色全体は templates/genba/concept.html の CSS 変数にある。
形はスライドの画像と見比べて合わせている。文言だけでなく、矢印・図の並びも元のとおりにする。
"""


def card(title='', text='', lines=(), sub='', label='', tone='', numbered=False, pairs=(), chip='', big_label=False,
         role=False):
    return {'title': title, 'text': text, 'lines': list(lines), 'sub': sub, 'label': label, 'tone': tone,
            'numbered': numbered, 'pairs': list(pairs), 'chip': chip, 'big_label': big_label, 'role': role}


def cards(cols, *items, grow=True):
    return {'type': 'cards', 'cols': cols, 'items': list(items), 'grow': grow}


def steps(*items, arrows=False):
    return {'type': 'steps', 'items': list(items), 'arrows': arrows}


def diagram(first, second, label, *stack):
    return {'type': 'diagram', 'first': first, 'second': second, 'label': label, 'stack': list(stack)}


def table(head, *rows, bold_first=False):
    return {'type': 'table', 'head': head, 'rows': list(rows), 'bold_first': bold_first}


def note(text, tone='', lead=''):
    return {'type': 'note', 'text': text, 'tone': tone, 'lead': lead}


def heading(text):
    return {'type': 'heading', 'text': text}


def flow(*items):
    return {'type': 'flow', 'items': list(items)}


def slide(kicker, title, *blocks, dark=False):
    return {'kind': 'slide', 'kicker': kicker, 'title': title, 'blocks': list(blocks), 'dark': dark}


def part(kicker, title, text, lines=()):
    return {'kind': 'part', 'kicker': kicker, 'title': title, 'text': text, 'lines': list(lines), 'blocks': []}


