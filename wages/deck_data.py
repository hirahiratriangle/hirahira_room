def slope_lines():
    """左右の行を結ぶ線。線を描く SVG は縦 72 の座標で、左の9行は1行 8、右の8行は1行 9 の高さにあたる。"""
    right_index = {name: i for i, (name, _) in enumerate(SLOPE_RIGHT)}
    lines = []
    for i, (name, _) in enumerate(SLOPE_LEFT):
        is_self = name.startswith('SE／PG')
        j = right_index['SE／PG' if is_self else name]
        lines.append({'y1': i * 8 + 4, 'y2': j * 9 + 4.5, 'self': is_self})
    # SE／PG の線を後に描いて、灰色の線の上に重ねる
    return sorted(lines, key=lambda line: line['self'])


