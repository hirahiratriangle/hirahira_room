"""このアプリが対象とする試験の定義。

試験ごとにアプリを作る方針のため、対象の試験と、問題を作るのに必要な資料を
ここ1か所で定義する。画面に出す案内も、利用者が自分の AI に渡すプロンプトも、
すべてこの定義から組み立てるので、書き換えれば全体が追随する。

別の試験に流用するときに触るのは、このファイルと data/categories.py の2つ。
"""

from .models import Category

EXAM = {
    'name': '銀行業務検定試験 法務3級',
    'short_name': '法務3級',
    'authority': '銀行業務検定協会',
    'url': 'https://www.kenteishiken.gr.jp/',
    'note': '問題の元は市販の問題解説集なので、問題 JSON は手元で作って手元の環境にだけ取り込む。',
    # 問題を作るのに必要な資料。required は「無いと質が大きく落ちるもの」。
    'materials': [
        {
            'name': '問題解説集（過去5回分）',
            'purpose': '本試験の問題・解答・解説・正解率。転記すれば正解が協会の出題に裏付けられる。',
            'required': True,
        },
        {
            'name': '出題範囲・出題項目一覧（同書の巻頭）',
            'purpose': '区分と出題項目。中分類と小分類の根拠になる。',
            'required': True,
        },
    ],
}


def material_lines():
    """プロンプトに差し込む資料の一覧。"""
    return [
        '- {}：{}'.format(m['name'], m['purpose'])
        for m in EXAM['materials']
    ]


def category_lines(subject=None, per_line=3):
    """プロンプトに差し込む分類の一覧。データベースの内容から作る。"""
    queryset = Category.objects.all()
    if subject:
        queryset = queryset.filter(subject=subject)
    parts = [
        '{} {}({})'.format(c.code, c.name, c.exam_weight)
        for c in queryset
    ]
    lines, current = [], []
    for part in parts:
        current.append(part)
        if len(current) == per_line:
            lines.append(' / '.join(current))
            current = []
    if current:
        lines.append(' / '.join(current))
    return lines


def build_prompt():
    """問題 JSON を作るときに AI に渡すプロンプトを組み立てる。

    資料の一覧と分類は定義とデータベースから引くので、分類を直しても内容がずれない。
    法務3級は学習モードを使わないので、技術解説（notes）は作らせない。取り込みの画面も
    notes 入りのファイルを弾く。ふだんの問題は問題解説集の OCR から組み立てスクリプトで
    作っており、このプロンプトは問題を書き足す・作り直すときのためのもの。
    """
    return '\n'.join([
        '{}の対策アプリ用に、問題をJSONで作ってください。'.format(EXAM['name']),
        '結果は .json ファイルに書き出してください。中身はJSONだけにし、',
        '説明文やコードブロックの記号は入れないでください。',
        '技術解説（"notes"）は作らないでください。このアプリは使わず、入っていると取り込めません。',
        '',
        '【手元に用意する資料】',
        '次の資料を参照してください。推測で作らないでください。',
        *material_lines(),
        '',
        '{',
        '  "questions": [',
        '  {',
        '    "category": 1,',
        '    "subject": "A",',
        '    "topic": "預金保険制度",',
        '    "difficulty": 2,',
        '    "stem": "問題文",',
        '    "choices": ["(1) の本文", "(2) の本文", "(3) の本文", "(4) の本文", "(5) の本文"],',
        '    "answer": 0,',
        '    "explanation": "正解の理由と、他の選択肢がなぜ違うか（根拠の条文・判例）",',
        '    "source": "出典（例：2025年10月 第162回 問2）"',
        '  }',
        '  ]',
        '}',
        '',
        '【問題（questions）の規則】',
        '- category は下の区分の番号。必須',
        '- subject は "A" のまま（法務3級は1科目）',
        '- topic は出題項目一覧の出題項目名をそのまま入れる',
        '- 本番と同じ五答択一にする。choices は5つ',
        '- choices に (1)〜(5) の記号は入れない（表示側で付ける）',
        '- answer は 0 から数える（(1) が 0）',
        '- difficulty は 1〜3。過去問は正解率から決める（70%以上 1、40%以上 2、それ未満 3）',
        '- キーは書かない',
        '- source は必ず書く。過去問は「2025年10月 第162回 問2」の形で始める。'
        '画面の「過去問」の札はこの書き出しで見分ける。自作したものは「自作（…）」とする',
        '- 同じ問いかけが回をまたいで出るので、取り込みは問題文と出典の回・問番号で問題を見分ける。'
        '回・問番号を書き換えると別の問題になり、解答履歴が切れる',
        '',
        '【このアプリが扱えないもの】',
        'このアプリは問題文も解説も「文字だけ」を表示する。画像を持つ仕組みがない。',
        '改行と全角スペースの字下げだけが保たれる。',
        '',
        '- **図が必要な問題は作らない。** 文字に落とすと設問として成立しないもの',
        '- 表やカレンダーは、改行と空白で並べれば読める。囲みの文章も改行で区切って stem に入れる',
        '- Markdown（#、-、*、**）と HTML タグは、記号がそのまま画面に出る。使わない',
        '- 上付き・下付き文字が表せない。「2のn乗」のように書く',
        '- ルビが表せない。PDF や OCR から抜いたときに読み仮名が別行に出ていたら取り除く',
        '- 選択肢を選ぶ形だけ。記述や並べ替えには対応しない',
        '- 正解は1つだけ。複数正解や部分点はない。空欄が複数ある問題は、'
        '「①分割譲渡　②一部譲渡　③確定後」のように組合せを1つの選択肢にまとめる',
        '- 同じ文字列の選択肢を2つ置けない（重複は取り込みで弾かれる）',
        '',
        '【区分（括弧内は本番50問での想定出題数）】',
        '0問の区分は2026年度の出題範囲から外れたもの。',
        *category_lines(subject='A'),
        '',
        '【誤答の作り方】',
        '混同しやすい近い制度・条文を誤答に置く。'
        'でたらめな誤答にすると消去法で解けてしまい学習にならない。',
        '',
        '【依頼】',
        'ここに、作ってほしい区分と問数を書き足してください。',
    ])
